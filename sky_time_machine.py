def timeline(tl):
    start, end = tl['start'], tl['end']
    span = max((end - start).days, 1)
    pos = lambda d: max(0, min(100, 100 * (d - start).days / span))
    html = '<div class="tl"><div class="line"></div>'
    html += ''.join(f'<i style="left:{pos(t):.2f}%"></i>' for t in tl['ticks'])
    if tl['a']:
        html += f'<b style="left:{pos(tl["a"]):.2f}%;background:#ffd166">A</b>'
    if tl['b']:
        html += f'<b style="left:{pos(tl["b"]):.2f}%;background:#70c8ff">B</b>'
    html += (f'<span class="lbl" style="left:0">{start.isoformat()}</span>'
             f'<span class="lbl" style="right:0">{end.isoformat()}</span></div>')
    st.markdown(html, unsafe_allow_html=True)
    st.caption(tl['note'])


