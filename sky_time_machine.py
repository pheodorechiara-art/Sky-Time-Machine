def build_context():
    """Draw the observation controls in the sidebar and compute the current image pair."""
    sb = st.sidebar
    sb.markdown('**OBSERVATION CONTROLS**')
    source = sb.radio('Image source', ['Simulated demonstration', 'Real SPHEREx FITS files'])
    simulated = source == 'Simulated demonstration'
    notices = []

    with sb.expander('Display and detection settings'):
        smooth = st.checkbox('Smooth image scaling', value=True)
        nsig = st.slider('Detection threshold (σ)', 4.0, 10.0, 5.0, 0.5,
                         help='A peak in the difference image must exceed this many times the image noise to become a candidate.')
        mover = st.checkbox('Simulated fast mover (demo)', value=True, disabled=not simulated)
        variable = st.checkbox('Simulated variability (demo)', value=True, disabled=not simulated)

    ctx = dict(ready=False, message='', simulated=simulated, notices=notices, smooth=smooth, nsig=nsig,
               variable=variable, target=None, target_name=None, band=None, wl=None, det=None,
               date_a=None, date_b=None, observations=None, sub_z=True, mask=False)

    if simulated:
        preset = sb.selectbox('Target', list(eng.TARGETS) + [CUSTOM])
        base = eng.TARGETS.get(preset, dict(ra=180.0, dec=0.0))
        ra_txt = sb.text_input('RA (deg or hh:mm:ss)', f"{base['ra']:.4f}", key=f'ra_{preset}')
        dec_txt = sb.text_input('Dec (deg or dd:mm:ss)', f"{base['dec']:.4f}", key=f'dec_{preset}')
        try:
            ra0, dec0 = eng.parse_coord(ra_txt, True), eng.parse_coord(dec_txt, False)
        except ValueError as exc:
            ctx['message'] = f'Could not read the coordinates: {exc}'
            return ctx
        target_name = preset if (preset in eng.TARGETS and abs(ra0 - base['ra']) < 0.002
                                 and abs(dec0 - base['dec']) < 0.002) else None
        target = eng.TARGETS.get(target_name) if target_name else None

        band = sb.slider('SPHEREx band (1-102)', 1, 102, 60,
                         help='SPHEREx observes in 102 wavelength bands from 0.75 to 5 micron.')
        det, wl = eng.band_info(band)
        sb.caption(f'Band {band} · detector {det} · about {wl:.2f} µm')
        date_a = sb.date_input('Epoch A', dt.date(2025, 6, 1), min_value=EPOCH_MIN, max_value=EPOCH_MAX)
        date_b = sb.date_input('Epoch B', dt.date(2026, 11, 1), min_value=EPOCH_MIN, max_value=EPOCH_MAX)

        if target:
            notices.append(('info', f"**{target_name}** - {target['kind']}. {target['note']} "
                                    "Coordinates and proper motions are approximate (verify in SIMBAD)."))
            if target['variable'] == 'dimming':
                notices.append(('caption', 'Illustrative dimming is centred on '
                                           f"{(eng.MISSION_START + dt.timedelta(days=300)).isoformat()}: put one epoch near it."))
            if target['variable'] == 'mira':
                notices.append(('caption', 'Illustrative pulsation period: 245.6 days. Choose epochs about half a period apart.'))
        else:
            notices.append(('info', 'Custom position: the simulated field contains generic stars only. This is not the real '
                                    'sky at these coordinates.'))

        pair = simulated_pair(ra0, dec0, target_name, band, date_a, date_b, mover, variable, smooth, nsig)
        label_a, label_b, pix = date_a.isoformat(), date_b.isoformat(), eng.PIX_ARCSEC
        days = abs((date_b - date_a).days)
        ticks = [eng.MISSION_START + dt.timedelta(days=182 * k) for k in range(5)]
        ctx.update(timeline=dict(ticks=ticks, a=date_a, b=date_b, start=EPOCH_MIN, end=EPOCH_MAX,
                                 note='Nominal two-year survey window. Ticks mark an illustrative six-month all-sky cadence; '
                                      'A and B are your chosen epochs. Simulated: not a list of real SPHEREx observations.'),
                   card=[('Data type', 'SIMULATED DEMONSTRATION - not SPHEREx data'),
                         ('Source', 'Generated by sky_engine in this app'),
                         ('Observation IDs', f"SIM-{(target_name or 'FIELD').replace(' ', '')}-B{band:03d}-{label_a} / ...-{label_b}"),
                         ('Dates and interval', f'{label_a} → {label_b} · {days} days ({days / 30.44:.1f} months)'),
                         ('Band', f'{band} of 102 · detector {det} · {wl:.2f} µm'),
                         ('Version / generated', f'{SIM_VERSION} · {dt.datetime.now(dt.timezone.utc):%Y-%m-%d %H:%M} UTC'),
                         ('Image model', f'{eng.PIX_ARCSEC} arcsec pixels, Gaussian PSF σ = {eng.PSF_SIGMA} px, white noise')],
                   target=target, target_name=target_name, band=band, wl=wl, det=det, date_a=date_a, date_b=date_b,
                   prov='sim')
    else:
        up = sb.file_uploader('SPHEREx FITS file(s): an IRSA cutout file (CUTOUT_INFO + IMAGE<i> extensions) or '
                              'Level-2 spectral images', type=['fits', 'fit', 'fts', 'gz'], accept_multiple_files=True)
        if not up:
            ctx['message'] = ('Upload SPHEREx FITS files in the sidebar to start (see About & Data → Real data guide). '
                              'Until then, try the simulated demonstration. The real-data path follows the documented '
                              'file structure but has not been tested on real files yet.')
            return ctx
        observations = []
        try:
            with st.spinner('Reading FITS files…'):
                for f in up:
                    observations += read_fits(f.getvalue(), f.name)
        except Exception as exc:
            ctx['message'] = f'Could not read the files: {exc}'
            return ctx
        if len(observations) < 2:
            ctx['message'] = 'Only one observation was found. Upload another file or a cutout file with several observations.'
            return ctx

        labels = []
        for i, o in enumerate(observations):
            wl_txt = f"{o['wavelength']:.3f} µm" if o['wavelength'] else 'wavelength n/a'
            labels.append(f"[{i}] {o['meta']['obs_id']} · {o['date'] or 'date unknown'} · {wl_txt}")
        guess = real.suggest_pair(observations)
        ia, ib = guess if guess else (0, 1)
        pa = sb.selectbox('Observation A (earlier)', range(len(observations)), index=ia, format_func=lambda i: labels[i])
        pb = sb.selectbox('Observation B (later)', range(len(observations)), index=ib, format_func=lambda i: labels[i])
        oa, ob = observations[pa], observations[pb]
        notices.append(('caption', 'A and B were pre-selected as the pair at nearly the same wavelength with the longest time '
                                   'separation.' if guess else 'No pair at matching wavelength was found automatically; choose A and B yourself.'))
        if oa['wavelength'] and ob['wavelength'] and abs(oa['wavelength'] - ob['wavelength']) / oa['wavelength'] > 0.01:
            notices.append(('warning', 'A and B are at different wavelengths. Differences may be spectral rather than changes over time.'))
        if pa == pb:
            notices.append(('warning', 'A and B are the same observation: the difference image will be empty.'))

        ra0 = sb.number_input('Field centre RA (deg)', 0.0, 360.0, float(round(oa['centre'][0], 5)), format='%.5f')
        dec0 = sb.number_input('Field centre Dec (deg)', -90.0, 90.0, float(round(oa['centre'][1], 5)), format='%.5f')
        fov = sb.slider('Field of view (arcmin)', 2.0, 30.0, 8.0, 0.5, help='Side length of the aligned comparison field.')
        sub_z = sb.checkbox('Subtract modelled zodiacal light (ZODI)', value=True,
                            help='The IMAGE extension is not zodiacal-light subtracted; the background changes with date.')
        mask = sb.checkbox('Mask flagged pixels (FLAGS ≠ 0)', value=False)
        pix = eng.PIX_ARCSEC
        n = int(np.clip(round(fov * 60 / pix), 32, 256))
        try:
            with st.spinner('Aligning observations on the sky…'):
                arr_a, arr_b, info = real.aligned_pair(oa, ob, ra0, dec0, n, pix, sub_z, mask)
        except Exception as exc:
            ctx['message'] = f'Could not align the observations: {exc}'
            return ctx
        pair = eng.build_pair(arr_a, arr_b, smooth=smooth, nsig=nsig, pix=pix)
        label_a, label_b = str(oa['date'] or labels[pa]), str(ob['date'] or labels[pb])
        days = abs((ob['date'] - oa['date']).days) if oa['date'] and ob['date'] else None
        dates = [o['date'] for o in observations if o['date']]
        if info['coverage'] < 0.9:
            notices.append(('warning', f"The two observations only overlap over {100 * info['coverage']:.0f}% of this field. "
                                       'Edges were filled with the median level.'))
        tl = None
        if dates:
            pad = dt.timedelta(days=max(5, (max(dates) - min(dates)).days // 20))
            tl = dict(ticks=sorted(dates), a=oa['date'], b=ob['date'], start=min(dates) - pad, end=max(dates) + pad,
                      note='Timeline of the observations found in your files (ticks), with A and B highlighted.')
        ctx.update(timeline=tl, observations=observations, sub_z=sub_z, mask=mask, target=None, prov='real',
                   obs_table=pd.DataFrame([{'#': i, 'File': o['meta']['file'], 'Observation': o['meta']['obs_id'],
                                            'Date': str(o['date'] or '-'), 'Wavelength (µm)': o['wavelength'],
                                            'Version': o['version']} for i, o in enumerate(observations)]),
                   card=[('Data type', 'REAL SPHEREx observations, as supplied in your files'),
                         ('Files', f"A: {oa['meta']['file']} · B: {ob['meta']['file']}"),
                         ('Source / checksum', f"{oa['meta']['source']} · sha256 {oa['meta']['sha']} / {ob['meta']['sha']}"),
                         ('Observations', f"A: {oa['meta']['obs_id']} · B: {ob['meta']['obs_id']}"),
                         ('Dates and interval', f"{oa['date'] or 'unknown'} → {ob['date'] or 'unknown'}"
                                                + (f' · {days} days ({days / 30.44:.1f} months)' if days is not None else '')),
                         ('Wavelength', f"A: {oa['wavelength'] or 'n/a'} µm · B: {ob['wavelength'] or 'n/a'} µm"),
                         ('Pipeline version', f"A: {oa['version'] or 'n/a'} · B: {ob['version'] or 'n/a'}"),
                         ('Processing', f"Units MJy/sr · zodi {'subtracted' if sub_z else 'not subtracted'} · "
                                        f"flagged pixels {'masked' if mask else 'kept'} ({100 * info['flagged_a']:.1f}% / "
                                        f"{100 * info['flagged_b']:.1f}% flagged) · bilinear resampling to a {n}×{n} px grid · "
                                        f"common coverage {100 * info['coverage']:.0f}%"),
                         ('Loaded', f'{dt.datetime.now(dt.timezone.utc):%Y-%m-%d %H:%M} UTC')])

    ctx.update(ready=True, pair=pair, ra0=ra0, dec0=dec0, pix=pix, n=pair['n'], label_a=label_a, label_b=label_b,
               days=days, years=(days / 365.25 if days else None))
    return ctx


