def plain_summary(pair, label_a, label_b, days):
    c = pair['cands']
    when = f'Between {label_a} and {label_b}' + (f' ({days} days apart)' if days is not None else '')
    if not c:
        return f'{when}, the tool found nothing that changed above the detection threshold.'
    text = f'{when}, the tool found {len(c)} unverified candidate(s). '
    for x in [c_ for c_ in c if c_['kind'] == 'moving'][:3]:
        rate = f", about {x['shift_arcsec'] / (days / 365.25):.1f} arcsec per year" if days else ''
        text += f"{x['id']} appears to have moved {x['shift_arcsec']:.1f} arcsec{rate}. "
    nb = sum(1 for x in c if x['kind'] == 'brightening')
    nd = sum(1 for x in c if x['kind'] == 'dimming')
    if nb or nd:
        text += f'{nb} source(s) got brighter and {nd} got fainter. '
    return text + 'Treat these as leads to check, not confirmed discoveries.'


def candidate_table(cands, ra0, dec0, n, pix, years):
    rows = []
    for c in cands:
        ra, dec = eng.pixel_to_radec(c['x'], c['y'], ra0, dec0, n, pix)
        row = {'ID': c['id'], 'Type': KIND_NAME[c['kind']], 'RA (deg)': round(ra, 4), 'Dec (deg)': round(dec, 4),
               'Shift (arcsec)': c['shift_arcsec']}
        if years:
            row['Rate (arcsec/yr)'] = round(c['shift_arcsec'] / years, 2) if c['kind'] == 'moving' else None
        row.update({'Significance (σ)': c['snr'], 'Symmetry': c['symmetry'], 'Expected false alarms': c['fa'],
                    'Reliability': c['reliability'], 'Status': 'Unverified candidate'})
        rows.append(row)
    return pd.DataFrame(rows)


