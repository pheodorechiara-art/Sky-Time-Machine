def candidate_page(ctx, simple):
    hero('03 · Candidate Explorer', 'Inspect every candidate',
         'Positions in A and B, displacement, significance, expected false alarms and a reliability label. '
         'Every candidate is unverified.')
    if not need_ctx(ctx):
        return
    provenance_chips(ctx)
    pair = ctx['pair']
    if not simple:
        with st.expander('How candidates are detected and scored'):
            st.markdown(
                "1. **Subtract** B − A and measure the noise as 1.4826 × the median absolute deviation.\n"
                "2. **Find peaks** brighter than the threshold (σ). A bright peak means the source is brighter in B; a dark peak, fainter.\n"
                "3. **Pair** a bright and a dark peak of similar strength within 25 px: that is a *moving source*. Its A and B positions are re-measured by centroiding each image.\n"
                "4. **Score**: *significance* = peak ÷ noise; *symmetry* = weaker ÷ stronger lobe; *expected false alarms* = pixels × erfc(σ/√2), the number of pure-noise peaks that strong expected per image.\n"
                "5. **Reliability**: High if fewer than 0.01 expected false alarms (and symmetry ≥ 0.6 for movers), Medium if fewer than 0.5, otherwise Low. A change under 10% of the source's brightness is also rated Low because it is more likely a calibration or resampling residual. This is a rule-based label, **not** a probability of being real.\n\n"
                "Real images have correlated noise and artefacts, so true false-alarm rates can be higher than the expectation shown.")
    if not pair['cands']:
        st.write('No candidates above the threshold. Try different dates, a different band, or a lower threshold.')
        return
    kinds = st.multiselect('Show types', list(KIND_NAME.values()), default=list(KIND_NAME.values()))
    levels = st.multiselect('Show reliability', ['High', 'Medium', 'Low'], default=['High', 'Medium', 'Low'])
    shown = [c for c in pair['cands'] if KIND_NAME[c['kind']] in kinds and c['reliability'] in levels]
    if not shown:
        st.write('No candidates match these filters.')
        return
    if not simple:
        show_df(candidate_table(shown, ctx['ra0'], ctx['dec0'], ctx['n'], ctx['pix'], ctx['years']))
    candidate_panel(dict(pair, cands=shown), ctx)


def candidate_panel(pair, ctx):
    ra0, dec0, pix, years, target = ctx['ra0'], ctx['dec0'], ctx['pix'], ctx['years'], ctx['target']
    ids = [c['id'] for c in pair['cands']]
    sel = st.selectbox('Inspect a candidate', ids)
    c = next(x for x in pair['cands'] if x['id'] == sel)
    n = pair['n']
    ra_a, dec_a = eng.pixel_to_radec(c['xa'], c['ya'], ra0, dec0, n, pix)
    ra_b, dec_b = eng.pixel_to_radec(c['xb'], c['yb'], ra0, dec0, n, pix)
    ra_c, dec_c = eng.pixel_to_radec(c['x'], c['y'], ra0, dec0, n, pix)
    left, right = st.columns([1.1, 1])
    with left:
        rows = [('Candidate', f"{c['id']} · {KIND_NAME[c['kind']]}"),
                ('Position', f'RA {ra_c:.4f}°, Dec {dec_c:.4f}° (pixel {c["x"]:.1f}, {c["y"]:.1f})')]
        if c['kind'] == 'moving':
            rows += [('Observation A', f'RA {ra_a:.4f}°, Dec {dec_a:.4f}° (pixel {c["xa"]:.1f}, {c["ya"]:.1f})'),
                     ('Observation B', f'RA {ra_b:.4f}°, Dec {dec_b:.4f}° (pixel {c["xb"]:.1f}, {c["yb"]:.1f})'),
                     ('Displacement', f'{c["shift_px"]:.2f} px = {c["shift_arcsec"]:.1f} arcsec'
                      + (f' ({c["shift_arcsec"] / years:.1f} arcsec/yr)' if years else ''))]
        else:
            rows.append(('Change', 'Brighter in B than in A' if c['kind'] == 'brightening' else 'Fainter in B than in A'))
        rows += [('Significance', f'{c["snr"]:.1f} σ above the difference-image noise'),
                 ('Expected false alarms', f'{c["fa"]:.3g} noise peaks this strong per image'),
                 ('Change vs source brightness', f'{min(c.get("frac", 0) * 100, 99):.0f}%'),
                 ('Reliability', f'{c["reliability"]}' + (f' (symmetry {c["symmetry"]:.2f})' if c['kind'] == 'moving' else '')),
                 ('Status', 'Unverified candidate')]
        if c.get('note'):
            rows.append(('Caution', c['note']))
        if target is not None:
            tb = eng.target_position(target, ctx['date_b'])
            off = math.hypot(c['x'] - tb[0], c['y'] - tb[1])
            rows.append(('Simulation truth', f'{off:.1f} px from the simulated target position at epoch B'
                         + (' → matches the simulated target' if off < 3 else '')))
        else:
            rows.append(('Cross-match', 'Not available in this version. Check SIMBAD, Gaia and WISE before drawing conclusions.'))
        card(rows)
    with right:
        a_img, b_img, d_img = eng.candidate_crops(pair, c)
        k1, k2, k3 = st.columns(3)
        with k1:
            show_img(a_img, 'A')
        with k2:
            show_img(b_img, 'B')
        with k3:
            show_img(d_img, 'B − A')
        st.caption('Cutouts are 24 × 24 pixels around the candidate, shown with the same intensity scale as the viewer.')


def spectral_page(ctx):
    hero('04 · Spectral Explorer', 'Explore the 102 infrared bands',
         'SPHEREx observes every position in 102 narrow wavelength bands from 0.75 to 5 micron. Use the band slider in '
         'the sidebar, and compare how the same field looks at different wavelengths.')
    if not need_ctx(ctx):
        return
    provenance_chips(ctx)
    if ctx['simulated']:
        panels = band_panels(ctx['ra0'], ctx['dec0'], ctx['target_name'], ctx['date_b'], ctx['variable'])
        cols = st.columns(3)
        for i, (b, w, img) in enumerate(panels):
            with cols[i % 3]:
                show_img(img, f'Band {b} · {w:.2f} µm (same intensity scale in all panels)')
        st.caption('The same field in six wavelength bands. Hot stars are brightest at short wavelengths; cool brown dwarfs '
                   'fade out toward short wavelengths and only appear in the longest bands.')
        if ctx['target']:
            spec = pd.DataFrame({'Wavelength (µm)': eng.WL,
                                 'Epoch A': eng.target_spectrum(ctx['target'], ctx['date_a'], ctx['variable']),
                                 'Epoch B': eng.target_spectrum(ctx['target'], ctx['date_b'], ctx['variable'])}).set_index('Wavelength (µm)')
            st.subheader(f"Simulated spectrum of {ctx['target_name']}")
            st.line_chart(spec)
            st.caption(f"Blackbody model across all 102 bands, not SPHEREx measurements. Selected band {ctx['band']}: {ctx['wl']:.2f} µm. "
                       'A variable star changes its spectrum between epochs A and B.')
    else:
        obs, n, pix = ctx['observations'], ctx['n'], ctx['pix']
        with_wl = sorted([o for o in obs if o['wavelength']], key=lambda o: o['wavelength'])
        if len(with_wl) < 2:
            st.info('Wavelength information is only available for IRSA cutout files (CUTOUT_INFO table).')
        else:
            k = st.slider('Number of wavelengths to show', 2, min(12, len(with_wl)), min(6, len(with_wl)))
            idx = np.linspace(0, len(with_wl) - 1, k).round().astype(int)
            thumbs = [(with_wl[i], real.aligned_pair(with_wl[i], with_wl[i], ctx['ra0'], ctx['dec0'], n, pix,
                                                     ctx['sub_z'], ctx['mask'])[0]) for i in idx]
            pooled = np.concatenate([t[1].ravel() for t in thumbs])
            lo, hi = float(np.percentile(pooled, 5)), float(np.percentile(pooled, 99.7))
            cols = st.columns(3)
            for j, (o, a_img) in enumerate(thumbs):
                with cols[j % 3]:
                    show_img(eng.thumbnail(a_img, max(1, 192 // n), lo, hi),
                             f"{o['wavelength']:.3f} µm · {o['date'] or 'date n/a'}")
            st.caption('The same sky position in different SPHEREx observations, ordered by wavelength, on one intensity scale. '
                       'Observations are from different dates, so changes can be spectral or temporal.')
    st.subheader('The 102 SPHEREx bands (approximate)')
    show_df(pd.DataFrame([{'Detector': d, 'Range (µm)': f'{lo:.2f}-{hi:.2f}', 'Bands': 17, 'First band': 17 * (d - 1) + 1}
                          for d, lo, hi in eng.DETECTORS]))


def validation_body():
    nsig = st.slider('Detection threshold for the validation run (σ)', 4.0, 10.0, 5.0, 0.5)
    with st.spinner('Running validation…'):
        rows, ctl = validation(nsig, 600)
    st.markdown('The pipeline is run on **simulated** data where the truth is known. These results validate the '
                'algorithm, not the real SPHEREx data path.')
    st.subheader('Challenge targets')
    show_df(pd.DataFrame([{
        'Target': r['target'], 'Band (µm)': r['wavelength'], 'Epochs': r['epochs'], 'Truth': r['expected'],
        'Detected': r['measured'], 'Reliability': r['reliability'], 'Simulated test': 'PASS' if r['passed'] else 'FAIL',
        'Real-data test': 'Pending: needs real SPHEREx files'} for r in rows]))
    passed = sum(r['passed'] for r in rows)
    st.markdown(f'**{passed} of {len(rows)}** simulated target tests passed. A motion test passes when the target is found as a '
                'moving source within 3 px of its true position with a shift within 25% of the truth; a variability test '
                'passes when the correct kind of change (brightening or dimming) is found at the target.')
    st.subheader('Negative controls')
    c1, c2, c3 = st.columns(3)
    c1.metric('Identical epochs → candidates', ctl['identical_epochs'], help='Must be 0: nothing changed.')
    c2.metric('False candidates per noise-only image', f"{ctl['false_per_image']:.3f}",
              help=f"Measured over {ctl['noise_trials']} simulated image pairs containing no real change.")
    c3.metric('Theoretical expectation', f"{ctl['expected_per_image']:.3f}", help='pixels × erfc(σ/√2) for white Gaussian noise.')
    st.caption(f"{ctl['images_with_false']} of {ctl['noise_trials']} noise-only image pairs produced at least one false candidate at {nsig:g} σ.")
    st.warning('These controls use white Gaussian noise. Real SPHEREx images have correlated noise, cosmic-ray hits and '
               'artefacts, so the false-alarm rate on real data can be higher. Real-data validation is still to be done.')


