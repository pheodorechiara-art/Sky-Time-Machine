@st.cache_data(show_spinner=False)
def simulated_pair(ra, dec, target_name, band, date_a, date_b, mover, variable, smooth, nsig):
    target = eng.TARGETS.get(target_name) if target_name else None
    a = eng.render_epoch(ra, dec, target, band, date_a, mover=mover, with_variability=variable)
    b = eng.render_epoch(ra, dec, target, band, date_b, mover=mover, with_variability=variable)
    return eng.build_pair(a, b, smooth=smooth, nsig=nsig)


@st.cache_data(show_spinner=False)
def band_panels(ra, dec, target_name, date, variable):
    target = eng.TARGETS.get(target_name) if target_name else None
    bands = [17 * d + 9 for d in range(6)]
    arrs = [eng.render_epoch(ra, dec, target, b, date, mover=False, with_variability=variable) for b in bands]
    pooled = np.concatenate([a.ravel() for a in arrs])
    lo, hi = float(np.percentile(pooled, 5)), float(np.percentile(pooled, 99.7))
    return [(b, eng.WL[b - 1], eng.thumbnail(a, 3, lo, hi)) for b, a in zip(bands, arrs)]


